# Builds the animation HTML from the approved primary logo SVG (geometry copied unchanged).
# Usage: python3 _work/build.py   (run from 05-designs/logo-animation/)
import re, pathlib
svg = pathlib.Path('../../04-identity/02-logo/demo-sidra-coffee_logo_primary-colour_ar_v01.svg').read_text(encoding='utf-8')
path_d = re.search(r'<path fill="#1F1B18" d="([^"]+)"', svg).group(1)
rects = re.findall(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)" fill="(#[0-9A-F]+)"', svg)
assert len(rects) == 7 and rects[3][4] == '#C23A20'
bars = '\n'.join(f'    <rect class="bar" data-x="{x}" x="{x}" y="{y}" width="{w}" height="{h}" fill="#1F1B18"/>' for x, y, w, h, _ in rects)
x4, y4, w4, h4, _ = rects[3]
html = f'''<!DOCTYPE html>
<html lang="ar">
<head>
<meta charset="utf-8">
<title>Sidra Coffee — logo animation, primary, AR, v01 (SYSTEM TEST, fictional client)</title>
<!-- 1080 x 1080 px, 3.0 s, 30 fps. Generated by _work/build.py from the approved primary logo SVG.
     The whole animation is a pure function of time: window.setTime(seconds). Opened in a browser it plays in real time and loops;
     add ?static (or prefers-reduced-motion) to show the final logo only. Timings are in the T object below. -->
<style>
  html, body {{ margin: 0; width: 1080px; height: 1080px; overflow: hidden; background: #F3ECE0; }}
  svg {{ position: absolute; left: 270px; top: 384.2px; width: 540px; height: 311.6px; display: block; overflow: visible; }}
</style>
</head>
<body>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 203.6 117.49" role="img" aria-label="سدرة">
  <!-- wordmark: one outlined path, faded in as a whole (never letter by letter, never wiped: a partial wipe hides the dots of the ة and misreads as ه) -->
  <path id="word" fill="#1F1B18" opacity="0" d="{path_d}"/>
  <g id="bars">
{bars}
    <rect id="lit" x="{x4}" y="{y4}" width="{w4}" height="0" fill="#C23A20"/>
  </g>
</svg>
<script>
// Timeline in seconds. Bars are indexed 0..6 from the left; they draw from the right (index 6) to the left (index 0).
const T = {{ total: 3.0, barStart: 0.10, barStagger: 0.12, barDur: 0.22, litStart: 1.14, litDur: 0.26, wordStart: 1.50, wordDur: 0.50 }};
const LIT_Y = {y4}, LIT_H = {h4};
const ease = p => 1 - Math.pow(1 - Math.min(1, Math.max(0, p)), 3);   // cubic ease-out, used for every move
const bars = [...document.querySelectorAll('.bar')], lit = document.getElementById('lit'), word = document.getElementById('word');
window.setTime = function (t) {{
  bars.forEach((b, i) => {{                       // each bar wipes in from its right edge
    const p = ease((t - T.barStart - (6 - i) * T.barStagger) / T.barDur), x = +b.dataset.x, w = 24.83;
    b.setAttribute('x', x + w * (1 - p)); b.setAttribute('width', w * p);
  }});
  const pl = ease((t - T.litStart) / T.litDur);   // Ember fills the fourth bar from the bottom up: flat colour, no blend
  lit.setAttribute('y', LIT_Y + LIT_H * (1 - pl)); lit.setAttribute('height', LIT_H * pl);
  const pw = ease((t - T.wordStart) / T.wordDur); // wordmark fades in as one piece, complete at every moment
  word.setAttribute('opacity', pw);
}};
const still = location.search.includes('static') || matchMedia('(prefers-reduced-motion: reduce)').matches;
if (location.search.includes('capture')) {{ window.setTime(0); }}
else if (still) {{ window.setTime(T.total); }}
else {{ const t0 = performance.now(); (function tick(now) {{ window.setTime(((now - t0) / 1000) % (T.total + 1)); requestAnimationFrame(tick); }})(t0); }}
</script>
</body>
</html>
'''
pathlib.Path('demo-sidra-coffee_logo-animation_primary_ar_v01.html').write_text(html, encoding='utf-8')
print('built', len(html))
